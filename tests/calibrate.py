"""Качество поиска и порог релевантности kb.MAX_DISTANCE.

1) Для вопросов «по базе» нужный раздел должен попасть в TOP_K, которые увидит модель (recall@K).
2) Порог: все вопросы по базе проходят; вопросы «мимо» по возможности отсекаются. Полностью развести группы
   по расстоянию нельзя («как приготовить борщ» близко к «дизайн-проект»), поэтому последний рубеж —
   правило в промпте: «нет ответа в базе — так и скажи». Это проверяет tests/live_answers.py.

    python tests/calibrate.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))
import kb  # noqa: E402

IN_KB = {
    "Сколько стоит ремонт санузла?": "Санузел под ключ", "какая гарантия на работы": "Срок гарантии",
    "можно жить в квартире пока идёт ремонт": "Можно ли жить в квартире во время ремонта",
    "есть рассрочка?": "Договор и оплата", "замер платный?": "Замер и смета", "вы работаете в Бердске?": "География",
    "кто покупает плитку": "Чистовые материалы", "сколько стоит дизайн проект": "Дизайн-проект",
    "во сколько начинаете шуметь": "Сколько бригада работает в день", "сносите несущие стены?": "Перепланировка",
    "скидка пенсионерам": "Скидки", "вывоз мусора сколько стоит": "Вывоз мусора",
    "капремонт двушки сколько по времени": "Капитальный ремонт", "можно ли сделать ремонт в новостройке": "Ремонт в новостройке",
    "а если плитка отвалится через год": "Что покрывает гарантия", "строите дома?": "Что мы не делаем",
}
OFF_KB = ["какая погода в Москве", "напиши стихотворение про кота", "сколько стоит айфон", "как приготовить борщ",
          "кто выиграл чемпионат мира", "переведи hello на французский", "посоветуй фильм", "как вылечить насморк"]

ok, worst_in = 0, 0.0
print(f"ПО БАЗЕ: место нужного раздела среди {kb.TOP_K}, которые получит модель")
for q, want in IN_KB.items():
    got = kb.search(q, max_distance=2.0)
    rank = next((i + 1 for i, c in enumerate(got) if c["section"] == want), None)
    d = next((c["distance"] for c in got if c["section"] == want), None)
    ok += bool(rank)
    worst_in = max(worst_in, d or 0)
    print(f"  {'✅' if rank else '❌'} {rank or '-'}  {d if d is not None else '':<6} {q}  → {want}")
outs = sorted((kb.search(q, top_k=1, max_distance=2.0)[0]["distance"], q) for q in OFF_KB)
print("МИМО БАЗЫ (лучшее расстояние):"); [print(f"  {d:.3f}  {q}") for d, q in outs]
cut = sum(d > kb.MAX_DISTANCE for d, _ in outs)
print(f"\nrecall@{kb.TOP_K}: {ok}/{len(IN_KB)} · худший нужный раздел {worst_in:.3f} · порог {kb.MAX_DISTANCE} "
      f"→ отсекает {cut}/{len(outs)} вопросов мимо базы")
sys.exit(0 if ok == len(IN_KB) and worst_in <= kb.MAX_DISTANCE else 1)
